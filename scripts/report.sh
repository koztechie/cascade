#!/usr/bin/env bash
# Shareable impact report (markdown) — one command, plain text, no browser.
# The credit-trail-style artifact: paste the output into a ticket or review.
set -euo pipefail

RELATE="${RELATE:-./bin/relate}"
STORE="${1:-store/catalog.rl}"
PARAMS="data/demo_params.json"

SKU=$(${PYTHON:-python3} -c "import json;print(json.load(open('$PARAMS'))['sku'])")
FROM=$(${PYTHON:-python3} -c "import json;print(json.load(open('$PARAMS'))['merge_from'])")
TO=$(${PYTHON:-python3} -c "import json;print(json.load(open('$PARAMS'))['merge_into'])")

echo "# Cascade impact report — \`${SKU}\`"
echo
echo "_Generated by \`make report\` from \`store/catalog.rl\`. Every table below is a live Cypher result; the statements live in \`queries/\`._"
echo
SUMMARY_JSON=$("$RELATE" query --database "$STORE" --read-only --param "sku=$SKU" --mode json < queries/parts/direct_counts.cypher)
CATEGORY_JSON=$("$RELATE" query --database "$STORE" --read-only --param "sku=$SKU" --mode json < queries/parts/category_machinery.cypher)
printf '%s\n%s' "$SUMMARY_JSON" "$CATEGORY_JSON" | SKU="$SKU" ${PYTHON:-python3} -c "
import json, os, sys
def parse(raw):
    try:
        d = json.loads(raw)
    except Exception:
        d = []
    if isinstance(d, dict):
        for k in ('rows', 'data', 'records', 'results'):
            if k in d:
                d = d[k]
                break
    if not isinstance(d, list) or not d or not isinstance(d[0], dict):
        return {}
    return d[0]
lines = [l for l in sys.stdin.read().splitlines() if l.strip()]
a = parse(lines[0]) if len(lines) > 0 else {}
b = parse(lines[1]) if len(lines) > 1 else {}
print('**Verdict:** delisting \`%s\` takes %d listing(s) offline, deadens %d page(s), breaks %d feed contract(s) and touches %d commercial object(s) — the direct consequences; the wider neighbourhood is context, not breakage.' % (
    os.environ['SKU'], a.get('listings', 0), a.get('pages', 0), b.get('feeds', 0),
    b.get('rules', 0) + b.get('campaigns', 0) + b.get('segments', 0)))
"
echo
echo "##1. What breaks if we stop selling \`${SKU}\`"
echo
echo "_Below: the4-hop neighbourhood — context, not breakage. Direct consequences are in the verdict above and sections2–3._"
echo
"$RELATE" query --database "$STORE" --read-only --param "sku=$SKU" --mode markdown < queries/parts/impact_summary.cypher
echo
echo "##2. Direct listings of \`${SKU}\`"
echo
"$RELATE" query --database "$STORE" --read-only --param "sku=$SKU" --mode markdown < queries/parts/report_listings.cypher
echo
echo "##3. Feed contracts on its category (what a delisting must satisfy)"
echo
"$RELATE" query --database "$STORE" --read-only --param "sku=$SKU" --mode markdown < queries/parts/report_feed_contracts.cypher
echo
echo "##4. Rejection risk pool (will fail the next feed sync)"
echo
"$RELATE" query --database "$STORE" --read-only --mode markdown < queries/05_rejection_risk.cypher
echo
echo "##5. Promo standing as of2026-12-09 (active vs expired)"
echo
"$RELATE" query --database "$STORE" --read-only --mode markdown < queries/06_active_vs_expired.cypher
echo
echo "##6. Dry run: merge \`${FROM}\` into \`${TO}\` — what collides"
echo
"$RELATE" query --database "$STORE" --read-only --param "from=$FROM" --param "to=$TO" --mode markdown < queries/04_merge_conflicts.cypher
echo
echo "##7. Remediation: the one fix that clears the risk"
echo
"$RELATE" query --database "$STORE" --read-only --mode markdown < queries/07_remediation.cypher
echo
echo "---"
echo "_End of report. Run \`make demo\` for the interactive version or open \`viewer.html\` for the graph._"

# Pass M1: the queries above opened the store read-write and re-randomized
# shard ids; restore the byte-stable form (stderr — stdout is the report).
${PYTHON:-python3} scripts/normalize_store.py "$STORE" >&2

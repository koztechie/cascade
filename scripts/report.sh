#!/usr/bin/env bash
# Shareable impact report (markdown) — one command, plain text, no browser.
# The credit-trail-style artifact: paste the output into a ticket or review.
set -euo pipefail

RELATE="${RELATE:-./bin/relate}"
STORE="${1:-store/catalog.rl}"
PARAMS="data/demo_params.json"
SKU=$(python3 -c "import json;print(json.load(open('$PARAMS'))['sku'])")
FROM=$(python3 -c "import json;print(json.load(open('$PARAMS'))['merge_from'])")
TO=$(python3 -c "import json;print(json.load(open('$PARAMS'))['merge_into'])")

echo "# Cascade impact report — \`${SKU}\`"
echo
echo "_Generated by \`make report\` from \`store/catalog.rl\`. Every table below is a live Cypher result; the statements live in \`queries/\`._"
echo
echo "##1. What breaks if we stop selling \`${SKU}\`"
echo
"$RELATE" query --database "$STORE" --param "sku=$SKU" --mode markdown <<'CYPHER'
MATCH (p:Product {sku: $sku})-[*1..4]-(x)
WHERE x:Listing OR x:Feed OR x:Rule OR x:Campaign OR x:Page OR x:Segment
RETURN labels(x)[0] AS impact_type, count(DISTINCT x) AS objects
ORDER BY objects DESC
CYPHER
echo
echo "##2. Direct listings of \`${SKU}\`"
echo
"$RELATE" query --database "$STORE" --param "sku=$SKU" --mode markdown <<'CYPHER'
MATCH (l:Listing)-[:OFFERS]->(p:Product {sku: $sku})
RETURN l.id AS listing, l.platform AS platform, l.status AS status
ORDER BY l.platform
CYPHER
echo
echo "##3. Feed contracts on its category (what a delisting must satisfy)"
echo
"$RELATE" query --database "$STORE" --param "sku=$SKU" --mode markdown <<'CYPHER'
MATCH (p:Product {sku: $sku})-[:IN_CATEGORY]->(c:Category)
      <-[:APPLIES_TO]-(m:Mapping)<-[:HAS_MAPPING]-(f:Feed)
RETURN f.name AS feed, m.target_field AS required_field, m.required AS required
CYPHER
echo
echo "##4. Rejection risk pool (will fail the next feed sync)"
echo
"$RELATE" query --database "$STORE" --mode markdown < queries/05_rejection_risk.cypher
echo
echo "##5. Promo standing as of2026-12-09 (active vs expired)"
echo
"$RELATE" query --database "$STORE" --mode markdown < queries/06_active_vs_expired.cypher
echo
echo "##6. Dry run: merge \`${FROM}\` into \`${TO}\` — what collides"
echo
"$RELATE" query --database "$STORE" --param "from=$FROM" --param "to=$TO" --mode markdown < queries/04_merge_conflicts.cypher
echo
echo "---"
echo "_End of report. Run \`make demo\` for the interactive version or open \`viewer.html\` for the graph._"
